/** Replaces {{token}} placeholders in a deterministic way. */
export function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

function dictionaryString(t: Dictionary, key: string): string | undefined {
  const value = (t as unknown as Record<string, unknown>)[key];
  return typeof value === 'string' ? value : undefined;
}

export function categoryLabel(t: Dictionary, id: string): string {
  return dictionaryString(t, id) ?? id;
}

export function categoryDescription(t: Dictionary, id: string): string {
  return dictionaryString(t, `${id}-desc`) ?? dictionaryString(t, `${id}Desc`) ?? '';
}
